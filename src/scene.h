#ifndef SCENE_H
#define SCENE_H

/* ============================================================
   scene = "ฉาก" หรือหน้าจอหนึ่งๆ ของเกม
   โมดูลนี้ทำหน้าที่แค่ "จดจำว่าตอนนี้อยู่ฉากไหน" (เหมือนโน้ตแปะตู้เย็น)
   ============================================================ */

/* รายชื่อฉากที่เป็นไปได้ (enum = ตั้งชื่อให้ตัวเลข จะได้อ่านง่าย) */
typedef enum {
    SCENE_MENU,   /* หน้าเมนูหลัก */
    SCENE_GAME    /* หน้าในเกม (กำลังเล่น) */
} SceneId;

/* ถามว่าตอนนี้อยู่ฉากไหน */
SceneId scene_get(void);

/* สั่งเปลี่ยนไปอีกฉากหนึ่ง */
void scene_set(SceneId id);

#endif /* SCENE_H */
